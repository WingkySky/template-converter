// pdf-text 纯几何重建的单元测试：文本项 → 行列矩阵。
// 几何模式仿照真实业务 PDF（身边云结算明细类）标定：字号 10、
// 折行表头三行视觉行（y 差 6）、列间隙 ≥20、格内空格间隙 5。
import { describe, expect, it } from 'vitest';
import { pdfTextItemsToRows } from '../../../src/core/parser/pdf-text';
import type { PdfTextItem } from '../../../src/core/parser/pdf-text';

const mk = (str: string, x: number, y: number, w = 10, h = 10): PdfTextItem => ({ str, x, y, w, h });

describe('pdfTextItemsToRows', () => {
  it('空输入返回空数组', () => {
    expect(pdfTextItemsToRows([])).toEqual([]);
  });

  it('同一视觉行按 x 间隙分格，不同视觉行分行', () => {
    const rows = pdfTextItemsToRows([
      mk('序号', 66, 100, 18), mk('姓名', 104, 100, 40),
      mk('1', 70, 80, 5), mk('张三', 110, 80, 20),
    ]);
    expect(rows).toEqual([['序号', '姓名'], ['1', '张三']]);
  });

  it('折行表头（上片段+居中行+下片段）合并为一行，同列多段拼回原词', () => {
    const rows = pdfTextItemsToRows([
      // 上片段行
      mk('服务人员', 104, 113, 40), mk('身份', 189, 113, 20),
      // 垂直居中的单行表头
      mk('序号', 66, 107, 18), mk('手机号码', 269, 107, 40), mk('银行卡开户行名称', 360, 107, 80),
      // 下片段行
      mk('姓名', 115, 101, 20), mk('证号', 189, 101, 20),
    ]);
    expect(rows).toEqual([['序号', '服务人员姓名', '身份证号', '手机号码', '银行卡开户行名称']]);
  });

  it('空白胶水项不参与区间计算（巨大宽度不跨列粘连），跨行拼接不留空格', () => {
    const rows = pdfTextItemsToRows([
      mk('服务人员', 104, 113, 40),
      mk(' ', 145, 113, 1400, 0), // 导出器写出的巨宽空白项
      mk('序号', 66, 107, 18),
      mk('姓名', 115, 101, 20),
    ]);
    expect(rows).toEqual([['序号', '服务人员姓名']]);
  });

  it('卡号内空格（格内小间隙）保持同格，纯数字格去空白', () => {
    const rows = pdfTextItemsToRows([
      mk('1', 70, 80, 5),
      mk('6222', 482, 80, 18), mk(' ', 501, 80, 4, 0), mk('0000', 506, 80, 18),
      mk(' ', 524, 80, 4, 0), mk('1234', 529, 80, 18), mk(' ', 548, 80, 4, 0), mk('5678', 552, 80, 18),
    ]);
    expect(rows).toEqual([['1', '6222000012345678']]);
  });

  it('稀疏行（含空单元格）仍按列带对齐，不串列', () => {
    const rows = pdfTextItemsToRows([
      // 表头（稠密行，参与建带）
      mk('序号', 66, 100, 18), mk('姓名', 104, 100, 40), mk('岗位', 200, 100, 20), mk('备注', 300, 100, 20), mk('结算金额', 400, 100, 40),
      // 稠密数据行
      mk('1', 70, 80, 5), mk('张三', 110, 80, 20), mk('录入', 205, 80, 20), mk('ok', 305, 80, 10), mk('3500.00', 405, 80, 36),
      // 稀疏行：缺姓名/岗位/备注
      mk('2', 70, 60, 5), mk('4200.00', 402, 60, 36),
    ]);
    expect(rows[2]).toEqual(['2', '', '', '', '4200.00']);
  });

  it('跨列长标题等稀疏行不参与建带，不撑爆列带', () => {
    const rows = pdfTextItemsToRows([
      mk('测试公司2026年9月结算明细', 209, 140, 300),
      mk('序号', 66, 100, 18), mk('姓名', 104, 100, 40), mk('结算金额', 400, 100, 40),
      mk('1', 70, 80, 5), mk('张三', 110, 80, 20), mk('3500.00', 405, 80, 36),
    ]);
    // 标题格 x 区间与「结算金额」列带重叠最大，按最大重叠归入该列（标题行位于表头之上，不影响下游）
    expect(rows).toEqual([
      ['', '', '测试公司2026年9月结算明细'],
      ['序号', '姓名', '结算金额'],
      ['1', '张三', '3500.00'],
    ]);
  });

  it('纯数字但不足 10 位的格不去空白语义（序号等保持原样）', () => {
    const rows = pdfTextItemsToRows([mk('12 34', 66, 100, 20)]);
    expect(rows).toEqual([['12 34']]);
  });
});
