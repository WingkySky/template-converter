// pdf-text 纯几何重建的单元测试：文本项 → 行列矩阵。
// 几何模式仿照真实业务 PDF（身边云结算明细类）标定：字号 10、
// 折行表头三行视觉行（y 差 6）、列间隙 ≥20、格内空格间隙 5。
import { describe, expect, it } from 'vitest';
import { pdfTextItemsToRows } from '../../../src/core/parser/pdf-text';
import type { PdfTextItem } from '../../../src/core/parser/pdf-text';

const mk = (str: string, x: number, y: number, w = 10, h = 10): PdfTextItem => ({ str, x, y, w, h });

describe('pdfTextItemsToRows', () => {
  it('空输入返回空数组', () => {
    expect(pdfTextItemsToRows([])).toEqual([]);
  });

  it('同一视觉行按 x 间隙分格，不同视觉行分行', () => {
    const rows = pdfTextItemsToRows([
      mk('序号', 66, 100, 18), mk('姓名', 104, 100, 40),
      mk('1', 70, 80, 5), mk('张三', 110, 80, 20),
    ]);
    expect(rows).toEqual([['序号', '姓名'], ['1', '张三']]);
  });

  it('折行表头（上片段+居中行+下片段）合并为一行，同列多段拼回原词', () => {
    const rows = pdfTextItemsToRows([
      // 上片段行
      mk('服务人员', 104, 113, 40), mk('身份', 189, 113, 20),
      // 垂直居中的单行表头
      mk('序号', 66, 107, 18), mk('手机号码', 269, 107, 40), mk('银行卡开户行名称', 360, 107, 80),
      // 下片段行
      mk('姓名', 115, 101, 20), mk('证号', 189, 101, 20),
    ]);
    expect(rows).toEqual([['序号', '服务人员姓名', '身份证号', '手机号码', '银行卡开户行名称']]);
  });

  it('空白胶水项不参与区间计算（巨大宽度不跨列粘连），跨行拼接不留空格', () => {
    const rows = pdfTextItemsToRows([
      mk('服务人员', 104, 113, 40),
      mk(' ', 145, 113, 1400, 0), // 导出器写出的巨宽空白项
      mk('序号', 66, 107, 18),
      mk('姓名', 115, 101, 20),
    ]);
    expect(rows).toEqual([['序号', '服务人员姓名']]);
  });

  it('卡号内空格（格内小间隙）保持同格，纯数字格去空白', () => {
    const rows = pdfTextItemsToRows([
      mk('1', 70, 80, 5),
      mk('6222', 482, 80, 18), mk(' ', 501, 80, 4, 0), mk('0000', 506, 80, 18),
      mk(' ', 524, 80, 4, 0), mk('1234', 529, 80, 18), mk(' ', 548, 80, 4, 0), mk('5678', 552, 80, 18),
    ]);
    expect(rows).toEqual([['1', '6222000012345678']]);
  });

  it('稀疏行（含空单元格）仍按列带对齐，不串列', () => {
    const rows = pdfTextItemsToRows([
      // 表头（稠密行，参与建带）
      mk('序号', 66, 100, 18), mk('姓名', 104, 100, 40), mk('岗位', 200, 100, 20), mk('备注', 300, 100, 20), mk('结算金额', 400, 100, 40),
      // 稠密数据行
      mk('1', 70, 80, 5), mk('张三', 110, 80, 20), mk('录入', 205, 80, 20), mk('ok', 305, 80, 10), mk('3500.00', 405, 80, 36),
      // 稀疏行：缺姓名/岗位/备注
      mk('2', 70, 60, 5), mk('4200.00', 402, 60, 36),
    ]);
    expect(rows[2]).toEqual(['2', '', '', '', '4200.00']);
  });

  it('跨列长标题等稀疏行不参与建带，不撑爆列带', () => {
    const rows = pdfTextItemsToRows([
      mk('测试公司2026年9月结算明细', 209, 140, 300),
      mk('序号', 66, 100, 18), mk('姓名', 104, 100, 40), mk('结算金额', 400, 100, 40),
      mk('1', 70, 80, 5), mk('张三', 110, 80, 20), mk('3500.00', 405, 80, 36),
    ]);
    // 标题格 x 区间与「结算金额」列带重叠最大，按最大重叠归入该列（标题行位于表头之上，不影响下游）
    expect(rows).toEqual([
      ['', '', '测试公司2026年9月结算明细'],
      ['序号', '姓名', '结算金额'],
      ['1', '张三', '3500.00'],
    ]);
  });

  it('纯数字但不足 10 位的格不去空白语义（序号等保持原样）', () => {
    const rows = pdfTextItemsToRows([mk('12 34', 66, 100, 20)]);
    expect(rows).toEqual([['12 34']]);
  });
});

describe('pdfTextItemsToRows 冠迪型密表（字号 5.39pt，开户行居中溢出压进邻列）', () => {
  // 几何按 2026-09-22 冠迪真实 PDF 实测坐标标定；文本内容全部虚构（张三/李四/1380000000x/虚构银行名）。
  // 锁定两个历史缺陷：① 溢出的开户行长名与手机号码物理重叠（左压 5.77pt）或仅隔 5.14pt 小间隙
  // 时被并进同一格；② 桥格把「手机号码/开户行」两条列带熔接，全表两列被 join 成一格。
  const gd = (str: string, x: number, y: number, w: number, h = 5.39): PdfTextItem => ({ str, x, y, w, h });

  it('溢出/小间隙的开户行不并格、不熔接列带，两列各自干净', () => {
    const rows = pdfTextItemsToRows([
      // 表头（列间隙 8.3~111pt）
      gd('序号', 22.08, 464.76, 10.78), gd('户名', 41.16, 464.76, 10.78),
      gd('手机号码', 163.68, 464.76, 21.61), gd(' ', 185.29, 464.76, 62.74, 0),
      gd('开户行', 232.34, 464.76, 16.17), gd(' ', 248.51, 464.76, 90.26, 0),
      gd('账号', 373.32, 464.76, 51.21),
      // 行 1：正常行（手机号码→开户行间隙 21.35pt）
      gd('1', 25.19, 452.52, 3.2), gd('张三', 41.16, 452.52, 10.78),
      gd('13800000001', 156.95, 452.52, 35.07), gd(' ', 192.02, 452.52, 21.35, 0),
      gd('虚构银行测试支行', 213.37, 452.52, 86.3), gd('6222000012345678', 373.32, 452.52, 51.21),
      // 行 2：开户行长名居中溢出，左端 186.25 压进手机号码格（物理重叠 5.77pt）
      gd('2', 25.19, 411.36, 3.2), gd('李四', 41.16, 411.36, 10.78),
      gd('13900000002', 156.95, 411.36, 35.07), gd(' ', 192.02, 411.36, 21.35, 0),
      gd('超长虚构银行名称居中溢出压进邻列测试支行', 186.25, 411.36, 108.23), gd('6222000012345679', 373.32, 411.36, 51.21),
      // 行 3：开户行较长但未重叠，与手机号码仅隔 5.14pt 小间隙
      gd('3', 25.19, 395.20, 3.2), gd('王五', 41.16, 395.20, 10.78),
      gd('13700000003', 156.95, 395.20, 35.07), gd(' ', 192.02, 395.20, 5.14, 0),
      gd('虚构银行股份有限公司超长测试支行', 197.16, 395.20, 86.62), gd('6222000012345670', 373.32, 395.20, 51.21),
    ]);
    expect(rows[0]).toEqual(['序号', '户名', '手机号码', '开户行', '账号']);
    expect(rows[1]).toEqual(['1', '张三', '13800000001', '虚构银行测试支行', '6222000012345678']);
    expect(rows[2]).toEqual(['2', '李四', '13900000002', '超长虚构银行名称居中溢出压进邻列测试支行', '6222000012345679']);
    expect(rows[3]).toEqual(['3', '王五', '13700000003', '虚构银行股份有限公司超长测试支行', '6222000012345670']);
  });
});
